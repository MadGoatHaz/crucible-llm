    /// Two streams, three content frames each arriving at 10/20/30 ms,
    /// completing at 30 ms; stream 0 TTFT 5 ms, stream 1 TTFT 15 ms.
    ///
    /// Built under a mocked quanta clock so every instant is exact — the
    /// deterministic fold assertions below depend on it.
    fn synthetic_events() -> Vec<PoolEvent> {
        let (clock, mock) = quanta::Clock::mock();
        quanta::with_clock(&clock, || {
            let t0 = MonotonicInstant::now(); // 0 ms
            mock.increment(5_000_000);
            let t3_0 = MonotonicInstant::now(); // 5 ms
            mock.increment(10_000_000);
            let t3_1 = MonotonicInstant::now(); // 15 ms
            mock.decrement(5_000_000);
            let at_1 = MonotonicInstant::now(); // 10 ms
            mock.increment(10_000_000);
            let at_2 = MonotonicInstant::now(); // 20 ms
            mock.increment(10_000_000);
            let at_3 = MonotonicInstant::now(); // 30 ms

            let mut events = Vec::new();
            for (stream, t3) in [(0u32, t3_0), (1u32, t3_1)] {
                for at in [at_1, at_2, at_3] {
                    let mut frame = frame_event(stream, ts_with_ttft(t0, t3));
                    // `frame_event` stamps `at` at the *current* mock time;
                    // overwrite with this frame's scheduled arrival.
                    match &mut frame {
                        PoolEvent::Frame { at: a, .. } => *a = at,
                        _ => unreachable!(),
                    }
                    events.push(frame);
                }
                events.push(PoolEvent::Complete {
                    stream,
                    timestamps: StreamTimestamps {
                        t0: Some(t0),
                        t1: Some(t0),
                        t2: Some(t3),
                        t3: Some(t3),
                        t_end: Some(at_3),
                    },
                    usage: Some(Usage {
                        prompt_tokens: 10,
                        completion_tokens: 3,
                    }),
                    premature: false,
                    malformed_frames: 0,
                });
            }
            events
        })
    }

