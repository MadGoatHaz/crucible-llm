//! Engine B — Concurrency & Saturation Curve Sweeper (plan Chunk 10,
//! blueprint §5 Engine B).
//!
//! A [`Sweep`] steps a configurable concurrency ladder (default
//! `1→2→4→8→16→32→64` simultaneous sessions), running a fixed workload
//! (one prompt, `max_tokens`) at `n` concurrent [`WorkerPool`] streams per
//! level, and collects per level:
//!
//! * **aggregate tokens/sec** — total tokens generated across *all* streams
//!   of the level divided by the level's wall time (blueprint: "System
//!   Generation Throughput (Aggregate Tokens/Sec across all streams)");
//! * **client-perceived p90 TPOT** — the 90th percentile of inter-token
//!   latencies pooled across *all* streams of the level (blueprint:
//!   "Client-Perceived Latency (p90 TPOT)");
//! * TTFT percentiles (one sample per stream), per-stream detail rows
//!   ([`StreamMetric`]), and completion/failure counts.
//!
//! The resulting [`SweepResult`] feeds the saturation knee-point detection
//! ([`SweepResult::detect_knee`] — the level where aggregate throughput
//! plateaus while p90 TPOT spikes, i.e. the memory-bandwidth-bound →
//! compute-bound transition) and the "Optimal Operational Envelope"
//! ([`SweepResult::envelope`] — the recommended sweet spot), and is the
//! data View 2 (Concurrency Matrix) renders with the knee highlighted.
//!
//! **Measurement isolation** (blueprint §4): all timing comes from the
//! workers' `quanta` stamps — the sweep only *consumes* tagged events. The
//! optional [`MetricsState`] publisher (the TUI seam) reads the same events
//! the sweep consumes and publishes in batches, so the render loop never
//! touches the timing path.

