    #[test]
    fn fold_level_computes_aggregate_tps_and_pooled_p90_tpot() {
        let events = synthetic_events();
        let mut acc = LevelAccumulator::new(2, 16);
        for e in &events {
            acc.on_event(e);
        }
        // 30 ms wall time.
        let level = acc.finish(30_000_000);
        assert_eq!(level.concurrency, 2);
        // usage (3 + 3) is the token source of truth.
        assert_eq!(level.total_tokens, 6);
        // 6 tokens / 0.03 s.
        assert!((level.aggregate_tps - 200.0).abs() < 0.01);
        // Every ITL sample is exactly 10 ms (4 samples, 2 streams); the
        // histogram reports it within its 3-significant-digit bucket
        // (10.0–10.1 ms).
        for v in [level.p50_tpot_ns, level.p90_tpot_ns, level.p99_tpot_ns] {
            assert!(
                (10_000_000..10_100_000).contains(&v),
                "ITL sample out of 10 ms bucket: {v}"
            );
        }
        assert_eq!(level.completed_streams, 2);
        assert_eq!(level.failed_streams, 0);
        assert_eq!(level.wall_ns, 30_000_000);
    }

    #[test]
    fn fold_level_records_ttft_and_per_stream_detail() {
        let events = synthetic_events();
        let mut acc = LevelAccumulator::new(2, 16);
        for e in &events {
            acc.on_event(e);
        }
        let level = acc.finish(30_000_000);
        // TTFTs: stream 0 → 5 ms (t3 - t1 from its first frame's
        // timestamps), stream 1 → 15 ms — each inside its histogram bucket.
        assert!(
            (5_000_000..5_010_000).contains(&level.ttft_p50_ns),
            "ttft p50: {}",
            level.ttft_p50_ns
        );
        assert!(
            (15_000_000..15_010_000).contains(&level.ttft_p90_ns),
            "ttft p90: {}",
            level.ttft_p90_ns
        );

        let s0 = &level.streams[0];
        let s1 = &level.streams[1];
        assert_eq!(s0.id, 0);
        assert_eq!(s1.id, 1);
        assert_eq!(s0.state, StreamStatus::Done);
        assert_eq!(s1.state, StreamStatus::Done);
        assert_eq!(s0.kind, "Content");
        assert_eq!(s0.pp_tokens, Some(10));
        assert_eq!(s0.tg_tokens, Some(3));
        assert!((s0.ttft_s.unwrap() - 0.005).abs() < 1e-9);
        assert!((s1.ttft_s.unwrap() - 0.015).abs() < 1e-9);
        // MTP = 3 tokens / 3 token frames = 1.0 (standard auto-regressive).
        assert!((s0.mtp.unwrap() - 1.0).abs() < 1e-9);
        // Generation speed = 3 tokens over the t3→t_end span.
        assert!(s0.gen_tps.is_some());
        assert!(s1.gen_tps.is_some());
        assert_eq!(s0.progress, 1.0);
    }

