/// The default concurrency ladder (blueprint §5 Engine B:
/// `1→2→4→8→16→32→64` simultaneous sessions).
pub const DEFAULT_LADDER: [usize; 7] = [1, 2, 4, 8, 16, 32, 64];

/// The stall-detection window for the *inter-token* phase: a worker that
/// has received at least one token and then goes silent for this long is
/// flagged (warned) as stalled. The per-worker timeout (the pool's
/// `worker_timeout`) is what eventually kills it.
pub const DEFAULT_STALL_TIMEOUT: Duration = Duration::from_secs(30);

/// The stall-detection floor for the *TTFB* phase (no token received
/// yet): at high concurrency the server batch-schedules, so a worker
/// waiting in the queue is *not* stalled — it gets this longer leash
/// (or the pool's per-worker timeout / 2, when that is larger) before a
/// warning fires.
pub const DEFAULT_TTFB_STALL_TIMEOUT: Duration = Duration::from_secs(90);

/// The cadence of the sweep's stall / step-budget checks (the drain
/// loop wakes on this interval between events).
const STALL_CHECK_INTERVAL: Duration = Duration::from_secs(5);

/// Normalize a user-supplied ladder: drop non-positive entries, remove
/// duplicates, sort ascending.
pub fn normalize_ladder(ladder: impl IntoIterator<Item = usize>) -> Vec<usize> {
    let mut v: Vec<usize> = ladder.into_iter().filter(|&n| n > 0).collect();
    v.sort_unstable();
    v.dedup();
    v
}

/// One ladder step of a [`Sweep`]: a point on the throughput/latency curve.
#[derive(Debug, Clone)]
pub struct SweepLevel {
    /// The concurrency of this step.
    pub concurrency: usize,
    /// System Generation Throughput: aggregate tokens/sec across all
    /// streams of the level.
    pub aggregate_tps: f64,
    /// Inter-token latency percentiles (ns), pooled across all streams.
    pub p50_tpot_ns: u64,
    pub p90_tpot_ns: u64,
    pub p99_tpot_ns: u64,
    /// TTFT percentiles (ns) — one sample per stream.
    pub ttft_p50_ns: u64,
    pub ttft_p90_ns: u64,
    /// Total tokens generated by every stream in the level.
    pub total_tokens: u64,
    /// Streams that completed (clean `[DONE]` or premature close).
    pub completed_streams: usize,
    /// Streams that failed (HTTP / connection / timeout / read error).
    pub failed_streams: usize,
    /// Workers killed by the per-worker timeout (the freeze fix). Their
    /// partial tokens are included in `total_tokens`.
    pub timed_out_streams: usize,
    /// `true` when the step-level timeout aborted the level (the sweep
    /// collected whatever it had and moved on to the next step).
    pub aborted: bool,
    /// Wall time of the level (spawn → last worker finished), in ns.
    pub wall_ns: u64,
    /// Per-stream detail (View 1 stream-matrix rows; blueprint §8
    /// `stream_metrics`).
    pub streams: Vec<StreamMetric>,
}

impl SweepLevel {
    /// p50 TPOT in milliseconds (for display).
    pub fn p50_tpot_ms(&self) -> f64 {
        self.p50_tpot_ns as f64 / 1_000_000.0
    }

    /// p90 TPOT in milliseconds (for display).
    pub fn p90_tpot_ms(&self) -> f64 {
        self.p90_tpot_ns as f64 / 1_000_000.0
    }

    /// p99 TPOT in milliseconds (for display).
    pub fn p99_tpot_ms(&self) -> f64 {
        self.p99_tpot_ns as f64 / 1_000_000.0
    }

    /// p50 TTFT in milliseconds.
    pub fn ttft_p50_ms(&self) -> f64 {
        self.ttft_p50_ns as f64 / 1_000_000.0
    }

    /// p90 TTFT in milliseconds.
    pub fn ttft_p90_ms(&self) -> f64 {
        self.ttft_p90_ns as f64 / 1_000_000.0
    }

    /// Level wall time in seconds.
    pub fn wall_secs(&self) -> f64 {
        self.wall_ns as f64 / 1_000_000_000.0
    }

    /// `true` when the level ran degraded: at least one worker was
    /// killed by the per-worker timeout, or the step was aborted by the
    /// step-level timeout. Its curve point is still usable (partial
    /// results were collected), but it should be treated with care in
    /// knee detection / the envelope.
    pub fn degraded(&self) -> bool {
        self.timed_out_streams > 0 || self.aborted
    }
}

/// The full sweep curve: one [`SweepLevel`] per ladder step.
#[derive(Debug, Clone, Default)]
pub struct SweepResult {
    pub levels: Vec<SweepLevel>,
}

impl SweepResult {
    /// `true` when no level ran.
    pub fn is_empty(&self) -> bool {
        self.levels.is_empty()
    }

    /// The level with the highest aggregate throughput — the fallback
    /// sweet spot when [`Self::detect_knee`] finds no saturation
    /// transition on the curve.
    pub fn peak_throughput(&self) -> Option<&SweepLevel> {
        self.levels
            .iter()
            .max_by(|a, b| a.aggregate_tps.total_cmp(&b.aggregate_tps))
    }

    /// Detect the saturation knee (blueprint §5 Engine B "Throughput
    /// Knee-Point Detection", plan Chunk 11).
    ///
    /// The knee is the *first* level (ascending concurrency) at which
    /// **both** hold relative to the previous level:
    ///
    /// 1. the aggregate-throughput gain drops to
    ///    [`KNEE_GAIN_THRESHOLD`] or below — throughput has plateaued;
    /// 2. the p90 TPOT grows by at least [`KNEE_SPIKE_THRESHOLD`]× —
    ///    client latency is spiking.
    ///
    /// That dual condition is the memory-bandwidth-bound (under-saturated)
    /// → compute-bound (saturated) transition. Returns [`None`] when the
    /// curve shows no such transition (fewer than two levels, throughput
    /// still climbing, or latency never spikes) — the envelope then falls
    /// back to [`Self::peak_throughput`].
    ///
    /// Pure function over the curve: no timing, no locks (measurement
    /// isolation, blueprint §4).
    pub fn detect_knee(&self) -> Option<KneePoint> {
        let mut levels: Vec<&SweepLevel> = self.levels.iter().collect();
        levels.sort_by_key(|l| l.concurrency);
        for (prev, cur) in levels.windows(2).map(|w| (w[0], w[1])) {
            let gain = relative_gain(prev.aggregate_tps, cur.aggregate_tps);
            let spike = relative_spike(prev.p90_tpot_ns, cur.p90_tpot_ns);
            if gain <= KNEE_GAIN_THRESHOLD && spike >= KNEE_SPIKE_THRESHOLD {
                return Some(KneePoint {
                    concurrency: cur.concurrency,
                    sweet_spot: prev.concurrency,
                    aggregate_tps: cur.aggregate_tps,
                    p90_tpot_ns: cur.p90_tpot_ns,
                });
            }
        }
        None
    }

    /// The "Optimal Operational Envelope" (blueprint §6 View 2): the
    /// recommended sweet spot for hosting this model on the target
    /// hardware — the level just before the detected knee, or the
    /// peak-throughput level when the curve is healthy (no knee).
    pub fn envelope(&self) -> Option<Envelope> {
        let knee = self.detect_knee();
        let sweet = match knee {
            Some(k) => k.sweet_spot,
            None => self.peak_throughput()?.concurrency,
        };
        let level = self.levels.iter().find(|l| l.concurrency == sweet)?;
        Some(Envelope {
            sweet_spot: level.concurrency,
            aggregate_tps: level.aggregate_tps,
            p90_tpot_ns: level.p90_tpot_ns,
            knee,
        })
    }
}

/// Relative aggregate-throughput gain at or below which a level is
/// considered to have *plateaued* (the knee's throughput condition).
pub const KNEE_GAIN_THRESHOLD: f64 = 0.05;

/// p90-TPOT growth factor (vs the previous level) at or above which a
/// level is considered to be *spiking* (the knee's latency condition).
pub const KNEE_SPIKE_THRESHOLD: f64 = 2.0;

/// The detected saturation knee: the first concurrency level where
/// aggregate throughput plateaus while p90 TPOT spikes (blueprint §5
/// Engine B — the memory-bandwidth-bound → compute-bound transition).
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct KneePoint {
    /// The concurrency at the knee (the first saturated level).
    pub concurrency: usize,
    /// The recommended sweet spot: the last level before the knee.
    pub sweet_spot: usize,
    /// Aggregate throughput (t/s) at the knee.
    pub aggregate_tps: f64,
    /// p90 TPOT (ns) at the knee — the spiking side.
    pub p90_tpot_ns: u64,
}

/// The "Optimal Operational Envelope" (blueprint §6 View 2): the
/// recommended sweet spot, with the detected knee (when the curve shows a
/// saturation transition) attached.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Envelope {
    /// The recommended concurrency (the sweet spot).
    pub sweet_spot: usize,
    /// Aggregate throughput (t/s) at the sweet spot.
    pub aggregate_tps: f64,
    /// p90 TPOT (ns) at the sweet spot.
    pub p90_tpot_ns: u64,
    /// The detected knee, if the curve showed a saturation transition.
    pub knee: Option<KneePoint>,
}

/// A concurrency ladder sweep (blueprint §5 Engine B).
///
/// One [`WorkerPool`] (shared connection-pooled client) is stepped through
/// the ladder level by level; each level runs to completion before the
/// next starts, so every curve point measures a steady population of
/// `n` concurrent streams.
#[derive(Clone)]
pub struct Sweep {
    pool: WorkerPool,
    ladder: Vec<usize>,
    /// Optional TUI seam: publish live [`MetricsSnapshot`]s while the sweep
    /// runs (the render loop reads them lock-free).
    metrics: Option<Arc<MetricsState>>,
    /// Optional sequence seam: publish `Concurrency level … (step …)` +
    /// streams active to the [`ProgressBus`] the Benchmark Sequence
    /// mirrors into the TUI's progress bar.
    progress: Option<Arc<ProgressBus>>,
    /// Optional `Space`-key pause gate: the sweep waits on it before
    /// spawning each ladder level (in-flight streams complete).
    pause: Option<Arc<RunPause>>,
    /// Optional run logger: the sweep records step starts / completions,
    /// per-worker timeouts, stalls, and step aborts.
    logger: Option<Arc<RunLogger>>,
    /// The inter-token stall-detection window (no tokens for this long →
    /// warn). The TTFB phase (no token yet) uses the longer
    /// [`DEFAULT_TTFB_STALL_TIMEOUT`] / `worker_timeout` / 2 threshold.
    stall_timeout: Duration,
    /// Optional hard cap on the computed step budget (tests use it to
    /// make a hanging level abort quickly; production leaves it `None`).
    step_budget_override: Option<Duration>,
}

impl std::fmt::Debug for Sweep {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("Sweep")
            .field("pool", &self.pool)
            .field("ladder", &self.ladder)
            .field("metrics", &self.metrics.is_some())
            .field("progress", &self.progress.is_some())
            .field("pause", &self.pause.is_some())
            .field("logger", &self.logger.is_some())
            .field("stall_timeout", &self.stall_timeout)
            .field("step_budget_override", &self.step_budget_override)
            .finish()
    }
}

impl Sweep {
    /// Create a sweep over `ladder` (normalized: positive, deduped,
    /// ascending). Use [`DEFAULT_LADDER`] for the blueprint default.
    pub fn new(pool: WorkerPool, ladder: impl IntoIterator<Item = usize>) -> Self {
        Self {
            pool,
            ladder: normalize_ladder(ladder),
            metrics: None,
            progress: None,
            pause: None,
            logger: None,
            stall_timeout: DEFAULT_STALL_TIMEOUT,
            step_budget_override: None,
        }
    }

    /// The (normalized) ladder this sweep steps through.
    pub fn ladder(&self) -> &[usize] {
        &self.ladder
    }

    /// Publish live snapshots to a shared [`MetricsState`] while the sweep
    /// runs (plan: the sweep coordinates the TUI's stream matrix / gauges
    /// via the Chunk 6 double buffer).
    pub fn metrics(mut self, state: Arc<MetricsState>) -> Self {
        self.metrics = Some(state);
        self
    }

    /// Attach a [`ProgressBus`] so the sweep reports its ladder position
    /// (`level`, `step`, streams active) to the Benchmark Sequence.
    pub fn progress(mut self, bus: Arc<ProgressBus>) -> Self {
        self.progress = Some(bus);
        self
    }

    /// Attach the `Space`-key pause gate: each ladder level waits on it
    /// before its `n` workers are spawned (the headless path leaves it
    /// `None`).
    pub fn pause(mut self, gate: Arc<RunPause>) -> Self {
        self.pause = Some(gate);
        self
    }

    /// Attach the run logger: the sweep then records its per-step
    /// lifecycle (start, worker timeouts, stalls, step aborts, summary)
    /// to the file-based log.
    pub fn logger(mut self, logger: Arc<RunLogger>) -> Self {
        self.logger = Some(logger);
        self
    }

    /// Override the inter-token stall-detection window (default
    /// [`DEFAULT_STALL_TIMEOUT`]). The TTFB phase (no token received
    /// yet) always uses the longer [`DEFAULT_TTFB_STALL_TIMEOUT`] (or the
    /// pool's per-worker timeout / 2, when that is larger).
    pub fn stall_timeout(mut self, d: Duration) -> Self {
        self.stall_timeout = d;
        self
    }

    /// Cap the computed step budget from above (a test hook: a hanging
    /// level can then be made to abort in seconds instead of minutes).
    pub fn step_budget(mut self, d: Duration) -> Self {
        self.step_budget_override = Some(d);
        self
    }

    fn logi(&self, ctx: Context, msg: String) {
        if let Some(l) = &self.logger {
            l.info(ctx, msg);
        }
    }

    fn logw(&self, ctx: Context, msg: String) {
        if let Some(l) = &self.logger {
            l.warn(ctx, msg);
        }
    }

    fn loge(&self, ctx: Context, msg: String) {
        if let Some(l) = &self.logger {
            l.error(ctx, msg);
        }
    }

    /// Run the full sweep: one level at a time, in ladder order.
    ///
    /// **The freeze fix:** each level is bounded three ways —
    ///
    /// 1. **per-worker timeout** (the pool's `worker_timeout`): a worker
    ///    that does not finish in time is killed and reported as a
    ///    `WorkerTimeout` failure with its partial tokens;
    /// 2. **stall detection**: a worker that received tokens and then
    ///    goes silent for [`DEFAULT_STALL_TIMEOUT`] is warned as
    ///    stalled; a worker still in the TTFB phase (no token yet) is
    ///    warned only after the longer
    ///    [`DEFAULT_TTFB_STALL_TIMEOUT`] / `worker_timeout` / 2 leash —
    ///    high-concurrency server queuing is not a stall (it
    ///    distinguishes a slow server from a hung connection — the
    ///    kill comes from #1);
    /// 3. **step-level timeout**: if the whole level runs past its budget
    ///    (3× the previous step, floored at the worker cap), it is
    ///    warned, and at 2× the budget the level is *aborted* — partial
    ///    results are collected, the level is marked `degraded`, and the
    ///    sweep continues to the next step. The sweep can never hang on
    ///    one bad level again.
    pub async fn run(&self) -> SweepResult {
        let mut levels = Vec::with_capacity(self.ladder.len());
        let mut prev_wall_ns = 0u64;
        self.logi(
            Context::EngineB,
            format!(
                "Engine B (Concurrency) started — ladder [{}]",
                self.ladder
                    .iter()
                    .map(|n| n.to_string())
                    .collect::<Vec<_>>()
                    .join(",")
            ),
        );
        for (i, &n) in self.ladder.iter().enumerate() {
            // The `Space`-key pause: hold before the next level's streams
            // go out (an in-flight level always completes).
            if let Some(gate) = &self.pause {
                gate.wait_while_paused().await;
            }
            let level = self
                .run_level(n, i + 1, self.ladder.len(), prev_wall_ns)
                .await;
            prev_wall_ns = level.wall_ns;
            levels.push(level);
        }
        self.logi(
            Context::EngineB,
            format!(
                "Engine B complete — {} level(s), {} degraded",
                levels.len(),
                levels.iter().filter(|l| l.degraded()).count()
            ),
        );
        SweepResult { levels }
    }

    /// The step-level budget: `max(worker cap, 3× the previous step's
    /// wall time)` — a level that is 3× slower than the one before it is
    /// suspect (saturation / a hung level); with no worker cap set, the
    /// budget is `3× previous` (or a generous 5-minute floor on the first
    /// step).
    /// The effective step budget: the computed value
    /// (`max(worker cap, 3× previous step)`) capped by the optional
    /// [`step_budget`](Self::step_budget) override.
    pub fn effective_step_budget(&self, prev_wall_ns: u64) -> Duration {
        const NO_CAP_FLOOR: Duration = Duration::from_secs(300);
        let computed = match self.pool.worker_timeout_cap() {
            Some(cap) => {
                if prev_wall_ns > 0 {
                    cap.max(Duration::from_nanos(prev_wall_ns.saturating_mul(3)))
                } else {
                    cap
                }
            }
            None => {
                if prev_wall_ns > 0 {
                    Duration::from_nanos(prev_wall_ns.saturating_mul(3))
                } else {
                    NO_CAP_FLOOR
                }
            }
        };
        self.step_budget_override
            .map(|o| o.min(computed))
            .unwrap_or(computed)
    }

    /// Run one ladder level: spawn `n` workers, drain the aggregate channel
    /// into a [`LevelAccumulator`], and fold the level's metrics.
    ///
    /// The drain loop is a `tokio::select!` between the event channel and
    /// a 5 s watchdog tick (stall detection + step-budget enforcement), so
    /// a level always ends: either every worker terminates (the channel
    /// closes) or the step timeout aborts it.
    async fn run_level(
        &self,
        n: usize,
        step: usize,
        total_steps: usize,
        prev_wall_ns: u64,
    ) -> SweepLevel {
        let start = MonotonicInstant::now();
        self.logi(
            Context::EngineB,
            format!("Step {step}/{total_steps}: concurrency={n}, spawning {n} worker(s)"),
        );
        if let Some(bus) = &self.progress {
            bus.publish(EngineProgress::Concurrency {
                level: n,
                step,
                total_steps,
                active: 0,
            });
        }
        let (mut rx, supervisor) = self.pool.clone().spawn_tagged(n, &format!("B{step}"));
        let mut acc = LevelAccumulator::new(n, self.pool.max_tokens());
        let budget = self.effective_step_budget(prev_wall_ns);
        let mut stall_tick = tokio::time::interval(STALL_CHECK_INTERVAL);
        stall_tick.set_missed_tick_behavior(tokio::time::MissedTickBehavior::Delay);
        let mut step_warned = false;
        let mut aborted = false;
        let mut batch = 0u32;
        loop {
            tokio::select! {
                event = rx.recv() => {
                    match event {
                        Some(e) => {
                            acc.on_event(&e);
                            self.log_pool_event(&e, &acc, step, total_steps);
                            batch += 1;
                            if let Some(state) = &self.metrics {
                                // Batched publish (blueprint §4.2: the
                                // engine "pushes unified snapshots per
                                // batch") — every 16 events, plus a final
                                // one when the level finishes.
                                if batch >= 16 {
                                    state.update(self.live_snapshot(&acc, n, &start, StreamStatus::Streaming));
                                    batch = 0;
                                }
                            }
                            // The progress bus shares the batch cadence:
                            // the live stream count is the "alive" signal
                            // while a level runs.
                            if let Some(bus) = &self.progress {
                                if batch >= 16 {
                                    bus.publish(EngineProgress::Concurrency {
                                        level: n,
                                        step,
                                        total_steps,
                                        active: acc.active(),
                                    });
                                }
                            }
                        }
                        // Channel closed ⇒ every worker has ended (or was
                        // killed); the level is done.
                        None => break,
                    }
                }
                _ = stall_tick.tick() => {
                    self.check_stalls(&mut acc, step, total_steps, &start);
                    let elapsed = start.elapsed();
                    if elapsed > budget {
                        if !step_warned {
                            step_warned = true;
                            self.logw(
                                Context::EngineB,
                                format!(
                                    "Step {step}/{total_steps}: running {:.1}s — past the {:.0}s budget (3× previous step / worker cap); workers still alive",
                                    elapsed.as_secs_f64(),
                                    budget.as_secs_f64()
                                ),
                            );
                        }
                        if elapsed > budget * 2 {
                            self.loge(
                                Context::EngineB,
                                format!(
                                    "Step {step}/{total_steps}: STEP TIMEOUT after {:.1}s (2× the {:.0}s budget) — aborting level, collecting partial results",
                                    elapsed.as_secs_f64(),
                                    budget.as_secs_f64()
                                ),
                            );
                            // Kill the supervisor task: it owns the worker
                            // tasks (its spawned children), so they are
                            // aborted with it; their sockets close.
                            supervisor.abort();
                            aborted = true;
                            break;
                        }
                    }
                }
            }
        }
        // On the normal path the supervisor resolves at the true end of
        // the level; after an `abort()` it returns a `JoinError`
        // immediately.
        let _outcomes: Option<Vec<crate::client::StreamOutcome>> = supervisor.await.ok();
        let wall_ns = start.delta_nanos(&MonotonicInstant::now());
        // Any worker still in flight (only possible after an abort) is
        // marked as a failed stream so the level's counts add up.
        acc.finalize_incomplete(aborted);
        if let Some(state) = &self.metrics {
            let status = if acc.failed() == n {
                StreamStatus::Error
            } else {
                StreamStatus::Done
            };
            state.update(self.live_snapshot(&acc, n, &start, status));
        }
        if let Some(bus) = &self.progress {
            bus.publish(EngineProgress::Concurrency {
                level: n,
                step,
                total_steps,
                active: acc.active(),
            });
        }
        let level = acc.finish(wall_ns, aborted);
        self.logi(
            Context::EngineB,
            format!(
                "Step {step}/{total_steps}: aggregate={:.1} t/s, p50={:.1}ms, p99={:.1}ms, {} completed, {} failed, {} timed out, {:.1}s{}",
                level.aggregate_tps,
                level.p50_tpot_ms(),
                level.p99_tpot_ms(),
                level.completed_streams,
                level.failed_streams,
                level.timed_out_streams,
                level.wall_secs(),
                if level.degraded() { " [DEGRADED]" } else { "" }
            ),
        );
        level
    }

    /// Stall detection: warn (once per worker) when a live worker has
    /// been silent past its *phase-appropriate* threshold:
    ///
    /// * **TTFB phase** (no token received yet): the worker is likely
    ///   queued at the server (batch-scheduling delay at high
    ///   concurrency), not stalled — it gets the longer
    ///   [`ttfb_stall_threshold`](Self::ttfb_stall_threshold) leash;
    /// * **inter-token phase** (at least one token received, then
    ///   silence): [`stall_timeout`](Self::stall_timeout) (default
    ///   30 s) — this *is* a real stall.
    ///
    /// A warning only — the kill comes from the per-worker timeout, so a
    /// *slow* server (tokens every 40 s) is distinguished from a *hung*
    /// connection (no tokens, ever) in the log.
    fn check_stalls(
        &self,
        acc: &mut LevelAccumulator,
        step: usize,
        total_steps: usize,
        start: &MonotonicInstant,
    ) {
        if self.logger.is_none() {
            return; // no observer → no work
        }
        let now = MonotonicInstant::now();
        for t in &mut acc.trackers {
            if t.finished {
                continue;
            }
            let ref_t = t.last_token_at.unwrap_or(*start);
            let idle_ns = ref_t.delta_nanos(&now);
            let threshold = if t.last_token_at.is_none() {
                self.ttfb_stall_threshold()
            } else {
                self.stall_timeout
            };
            if (idle_ns as u128) >= threshold.as_nanos() && !t.stall_warned {
                t.stall_warned = true;
                if t.last_token_at.is_none() {
                    // TTFB phase: no token yet — the server is queuing
                    // this level's concurrent requests (normal at high
                    // concurrency), not stalled.
                    self.logw(
                        Context::EngineB,
                        format!(
                            "Step {step}/{total_steps}: worker #{} awaiting first token (TTFB: {:.0}s) — server queuing {} concurrent requests",
                            t.id,
                            idle_ns as f64 / 1e9,
                            acc.n
                        ),
                    );
                } else {
                    // Inter-token phase: at least one token arrived, then
                    // silence — a real stall.
                    let last = t
                        .last_token_wall
                        .map(|w| {
                            let ms = w
                                .duration_since(UNIX_EPOCH)
                                .map(|d| d.as_millis() as u64)
                                .unwrap_or(0);
                            crate::log::format_timestamp(ms, false)
                        })
                        .unwrap_or_else(|| "unknown".to_string());
                    self.logw(
                        Context::EngineB,
                        format!(
                            "Step {step}/{total_steps}: worker #{} stalled: no tokens for {:.0}s (last token at {last})",
                            t.id,
                            idle_ns as f64 / 1e9
                        ),
                    );
                }
            }
        }
    }

    /// The TTFB-phase stall threshold: the pool's per-worker timeout / 2
    /// when one is set (the kill is the full cap, so half of it is a
    /// reasonable "queued, not hung" warning point), floored at
    /// [`DEFAULT_TTFB_STALL_TIMEOUT`] (90 s).
    fn ttfb_stall_threshold(&self) -> Duration {
        self.pool
            .worker_timeout_cap()
            .map(|cap| (cap / 2).max(DEFAULT_TTFB_STALL_TIMEOUT))
            .unwrap_or(DEFAULT_TTFB_STALL_TIMEOUT)
    }

    /// Log the per-worker terminal events (stream complete / failure).
    /// Token-reception milestones (first token, every 50th) are logged by
    /// the workers themselves (the `B{step}-{id}` tags).
    fn log_pool_event(
        &self,
        e: &PoolEvent,
        acc: &LevelAccumulator,
        step: usize,
        total_steps: usize,
    ) {
        match e {
            PoolEvent::Complete { stream, .. } => {
                let tokens = acc
                    .trackers
                    .get(*stream as usize)
                    .map(|t| t.tokens())
                    .unwrap_or(0);
                self.logi(
                    Context::Sse,
                    format!("B{step}-{stream} stream complete: {tokens} tokens"),
                );
            }
            PoolEvent::Failed { stream, error, .. } => {
                let tokens = acc
                    .trackers
                    .get(*stream as usize)
                    .map(|t| t.tokens())
                    .unwrap_or(0);
                match error {
                    StreamError::WorkerTimeout(d) => self.logw(
                        Context::EngineB,
                        format!(
                            "Step {step}/{total_steps}: worker #{stream} TIMEOUT after {d:?} — collected {tokens} tokens (killed)",
                        ),
                    ),
                    StreamError::Timeout(d) => self.logw(
                        Context::EngineB,
                        format!(
                            "Step {step}/{total_steps}: worker #{stream} stalled — no data for {d:?} (killed)",
                        ),
                    ),
                    other => self.loge(
                        Context::EngineB,
                        format!(
                            "Step {step}/{total_steps}: worker #{stream} failed: {other} (collected {tokens} tokens)",
                        ),
                    ),
                }
            }
            PoolEvent::Frame { .. } => {}
        }
    }

    /// The live (in-level) snapshot published to the TUI seam.
    fn live_snapshot(
        &self,
        acc: &LevelAccumulator,
        n: usize,
        start: &MonotonicInstant,
        status: StreamStatus,
    ) -> MetricsSnapshot {
        let elapsed_ns = start.delta_nanos(&MonotonicInstant::now()).max(1);
        let tokens = acc.tokens_so_far();
        let snapshot = MetricsSnapshot {
            endpoint: self.pool.endpoint().to_string(),
            model: self.pool.model().to_string(),
            mode: "Concurrency".to_string(),
            aggregate_tps: tokens as f64 / (elapsed_ns as f64 / 1_000_000_000.0),
            // Server-reported prompt totals (usage frames): the metrics
            // seam derives `prompt_throughput` = prompt / mean TTFT from
            // this plus the per-stream TTFTs.
            prompt_tokens: acc.prompt_tokens_so_far(),
            active_streams: acc.active(),
            total_streams: n,
            status,
            streams: acc.stream_rows(),
            ..Default::default()
        };
        snapshot.with_itl_percentiles(acc.itl())
    }
}

/// Per-stream state folded from the aggregate channel while a level runs.
struct StreamTracker {
    id: u32,
    state: StreamStatus,
    reasoning_frames: u64,
    content_frames: u64,
    /// All data frames received (MTP packet denominator, blueprint §7).
    packets: u64,
    last_token_at: Option<MonotonicInstant>,
    /// Wall-clock time of the last token (the stall log's "last token at
    /// HH:MM:SS" — a display concern, never on the quanta timing path).
    last_token_wall: Option<SystemTime>,
    ttft_ns: Option<u64>,
    t3: Option<MonotonicInstant>,
    t_end: Option<MonotonicInstant>,
    usage: Option<Usage>,
    premature: bool,
    error: Option<String>,
    finished: bool,
    /// The stall warning has fired for this worker (once per worker).
    stall_warned: bool,
    /// `true` when this worker was killed by the per-worker timeout.
    timed_out: bool,
}

impl StreamTracker {
    fn new(id: u32) -> Self {
        Self {
            id,
            state: StreamStatus::Waiting,
            reasoning_frames: 0,
            content_frames: 0,
            packets: 0,
            last_token_at: None,
            last_token_wall: None,
            ttft_ns: None,
            t3: None,
            t_end: None,
            usage: None,
            premature: false,
            error: None,
            finished: false,
            stall_warned: false,
            timed_out: false,
        }
    }

    /// Token frames seen (reasoning + content).
    fn token_frames(&self) -> u64 {
        self.reasoning_frames + self.content_frames
    }

    /// Tokens generated: server-reported `usage` when available, else the
    /// counted token frames (one token per frame is the worker's unit).
    fn tokens(&self) -> u64 {
        self.usage
            .map(|u| u.completion_tokens)
            .unwrap_or_else(|| self.token_frames())
    }

    /// The stream-matrix `TYPE` column: the dominant phase.
    fn kind(&self) -> String {
        if self.reasoning_frames > self.content_frames {
            "Reasoning".to_string()
        } else if self.content_frames > 0 {
            "Content".to_string()
        } else {
            "Control".to_string()
        }
    }

    fn row(&self, max_tokens: u32) -> StreamMetric {
        let tg = self.tokens();
        let ttft_s = self.ttft_ns.map(|ns| ns as f64 / 1_000_000_000.0);
        let gen_tps = match (self.t3, self.t_end) {
            (Some(t3), Some(end)) => {
                let span_s = t3.delta_nanos(&end) as f64 / 1_000_000_000.0;
                if span_s > 0.0 && tg > 0 {
                    Some(tg as f64 / span_s)
                } else {
                    None
                }
            }
            _ => None,
        };
        // MTP = output tokens / token-carrying packets (blueprint §7.4;
        // matches the Chunk 7 single-stream formula).
        let mtp = {
            let pk = self.token_frames();
            if pk > 0 {
                Some(tg as f64 / pk as f64)
            } else {
                None
            }
        };
        let progress = if self.finished {
            1.0
        } else if max_tokens > 0 {
            (tg as f64 / max_tokens as f64).min(1.0)
        } else {
            0.0
        };
        StreamMetric {
            id: self.id,
            kind: self.kind(),
            state: self.state,
            pp_tokens: self.usage.map(|u| u.prompt_tokens),
            tg_tokens: (tg > 0).then_some(tg),
            ttft_s,
            gen_tps,
            mtp,
            progress,
        }
    }
}

/// The per-level fold: pooled ITL / TTFT histograms plus one
/// [`StreamTracker`] per worker.
struct LevelAccumulator {
    n: usize,
    max_tokens: u32,
    /// Inter-token latencies pooled across all streams (TPOT).
    itl: LatencyHistogram,
    /// One TTFT sample per stream.
    ttft: LatencyHistogram,
    trackers: Vec<StreamTracker>,
}

impl LevelAccumulator {
    fn new(n: usize, max_tokens: u32) -> Self {
        Self {
            n,
            max_tokens,
            itl: LatencyHistogram::default(),
            ttft: LatencyHistogram::default(),
            trackers: (0..n).map(|i| StreamTracker::new(i as u32)).collect(),
        }
    }

    /// Fold one pooled event (the sweep's drain-loop hot path).
    ///
    /// The ITL sample is captured *before* taking the tracker's mutable
    /// borrow: `self.trackers` and `self.itl` are disjoint fields, so the
    /// sample (a plain `u64`) can be recorded while the tracker borrow is
    /// still live.
    fn on_event(&mut self, event: &PoolEvent) {
        match event {
            PoolEvent::Frame {
                frame,
                at,
                timestamps,
                stream,
            } => {
                let sample = self
                    .trackers
                    .get(*stream as usize)
                    .and_then(|t| t.last_token_at)
                    .map(|prev| prev.delta_nanos(at));
                let Some(t) = self.trackers.get_mut(*stream as usize) else {
                    return;
                };
                t.packets += 1;
                match &frame.chunk {
                    Chunk::Reasoning(_) => t.reasoning_frames += 1,
                    Chunk::Content(_) => t.content_frames += 1,
                    Chunk::Control | Chunk::Usage(_) => {}
                }
                if is_token_frame(&frame.chunk) {
                    if let Some(ns) = sample {
                        self.itl.record(ns);
                    }
                    t.last_token_at = Some(*at);
                    t.last_token_wall = Some(SystemTime::now());
                    if t.t3.is_none() {
                        t.t3 = Some(*at);
                    }
                    if t.state == StreamStatus::Waiting {
                        t.state = StreamStatus::Streaming;
                    }
                }
                if t.ttft_ns.is_none() {
                    t.ttft_ns = timestamps.ttft_nanos();
                }
            }
            PoolEvent::Complete {
                stream,
                timestamps,
                usage,
                premature,
                ..
            } => {
                let Some(t) = self.trackers.get_mut(*stream as usize) else {
                    return;
                };
                t.usage = *usage;
                t.premature = *premature;
                t.t_end = timestamps.t_end;
                if t.ttft_ns.is_none() {
                    t.ttft_ns = timestamps.ttft_nanos();
                }
                t.state = StreamStatus::Done;
                t.finished = true;
            }
            PoolEvent::Failed {
                stream,
                timestamps,
                error,
            } => {
                let Some(t) = self.trackers.get_mut(*stream as usize) else {
                    return;
                };
                t.t_end = timestamps.t_end;
                if t.ttft_ns.is_none() {
                    t.ttft_ns = timestamps.ttft_nanos();
                }
                t.timed_out = matches!(error, crate::client::StreamError::WorkerTimeout(_));
                t.error = Some(error.to_string());
                t.state = StreamStatus::Error;
                t.finished = true;
            }
        }
    }

    /// Token frames received so far (live-snapshot throughput numerator).
    fn tokens_so_far(&self) -> u64 {
        self.trackers.iter().map(|t| t.token_frames()).sum()
    }

    /// Prompt tokens reported by server `usage` so far (live-snapshot
    /// prompt-throughput numerator; the per-stream `pp_tokens` rows carry
    /// the same data for the UI's stream detail).
    fn prompt_tokens_so_far(&self) -> u64 {
        self.trackers
            .iter()
            .filter_map(|t| t.usage.map(|u| u.prompt_tokens))
            .sum()
    }

    /// Streams actively receiving tokens.
    fn active(&self) -> usize {
        self.trackers
            .iter()
            .filter(|t| t.state == StreamStatus::Streaming)
            .count()
    }

    /// Failed streams.
    fn failed(&self) -> usize {
        self.trackers
            .iter()
            .filter(|t| t.state == StreamStatus::Error)
            .count()
    }

    /// Per-stream detail rows (stream matrix / `stream_metrics`).
    fn stream_rows(&self) -> Vec<StreamMetric> {
        self.trackers
            .iter()
            .map(|t| t.row(self.max_tokens))
            .collect()
    }

    /// &self accessor for the ITL histogram (live-snapshot percentiles).
    fn itl(&self) -> &LatencyHistogram {
        &self.itl
    }

    /// Mark every worker that never reached a terminal event as failed.
    ///
    /// Only reachable after a step-level abort (on the normal channel-close
    /// path every worker has emitted exactly one terminal event, so there
    /// is nothing to finalize).
    fn finalize_incomplete(&mut self, aborted: bool) {
        for t in &mut self.trackers {
            if t.finished {
                continue;
            }
            t.finished = true;
            t.state = StreamStatus::Error;
            t.t_end = Some(MonotonicInstant::now());
            t.error = Some(if aborted {
                "aborted (step timeout)".to_string()
            } else {
                "incomplete (level ended)".to_string()
            });
        }
    }

    /// Fold the finished level into its [`SweepLevel`] curve point.
    fn finish(mut self, wall_ns: u64, aborted: bool) -> SweepLevel {
        let total_tokens: u64 = self.trackers.iter().map(|t| t.tokens()).sum();
        for t in &self.trackers {
            if let Some(ns) = t.ttft_ns {
                self.ttft.record(ns);
            }
        }
        let wall_ns = wall_ns.max(1);
        SweepLevel {
            concurrency: self.n,
            aggregate_tps: total_tokens as f64 / (wall_ns as f64 / 1_000_000_000.0),
            p50_tpot_ns: self.itl.p50() as u64,
            p90_tpot_ns: self.itl.p90() as u64,
            p99_tpot_ns: self.itl.p99() as u64,
            ttft_p50_ns: self.ttft.p50() as u64,
            ttft_p90_ns: self.ttft.p90() as u64,
            total_tokens,
            completed_streams: self
                .trackers
                .iter()
                .filter(|t| t.state == StreamStatus::Done)
                .count(),
            failed_streams: self.failed(),
            timed_out_streams: self.trackers.iter().filter(|t| t.timed_out).count(),
            aborted,
            wall_ns,
            streams: self.stream_rows(),
        }
    }
}

/// A frame carrying generated tokens (reasoning or content) — a `Usage` /
/// `Control` frame is not a token arrival (mirrors the Chunk 5 worker).
fn is_token_frame(chunk: &Chunk) -> bool {
    matches!(chunk, Chunk::Reasoning(_) | Chunk::Content(_))
}

/// Relative throughput change `prev → cur` (`(cur − prev) / prev`).
///
/// A non-positive baseline with a positive `cur` is treated as infinite
/// growth (never a plateau); a zero/zero pair is no change.
fn relative_gain(prev: f64, cur: f64) -> f64 {
    if prev <= 0.0 {
        return if cur > 0.0 { f64::INFINITY } else { 0.0 };
    }
    (cur - prev) / prev
}

/// Relative p90-TPOT change `prev → cur` (`cur / prev`).
///
/// A zero baseline with a positive `cur` is treated as an infinite spike;
/// a zero/zero pair is no change.
fn relative_spike(prev_ns: u64, cur_ns: u64) -> f64 {
    if prev_ns == 0 {
        return if cur_ns > 0 { f64::INFINITY } else { 0.0 };
    }
    cur_ns as f64 / prev_ns as f64
}

